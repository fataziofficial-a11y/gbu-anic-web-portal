def money(v: int) -> str:
    return f"{v:,}".replace(",", " ") + " руб. 00 коп."


def new_doc():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2)
        s.top_margin = s.bottom_margin = Cm(1.5)
    return doc


def mk(doc):
    def p(text="", bold=False, align=None, size=None, space_after=4):
        par = doc.add_paragraph()
        run = par.add_run(text)
        run.bold = bold
        if size:
            run.font.size = Pt(size)
        if align:
            par.alignment = align
        par.paragraph_format.space_after = Pt(space_after)
        return par

    def h(text):
        p(text, bold=True, space_after=6)

    def bullets(items):
        for it in items:
            par = doc.add_paragraph(style="List Bullet")
            par.add_run(it).font.size = Pt(11)
            par.paragraph_format.space_after = Pt(2)
            par.paragraph_format.left_indent = Cm(0.8)

    def signatures(d):
        table = d.add_table(rows=2, cols=2)
        table.style = "Table Grid"
        table.rows[0].cells[0].paragraphs[0].add_run("Заказчик:").bold = True
        table.rows[0].cells[1].paragraphs[0].add_run("Исполнитель:").bold = True
        for cell, lines, post, sign in (
            (table.rows[1].cells[0], CUSTOMER, "Вр.и.о. директора",
             "_______________ / Хохолов А.А."),
            (table.rows[1].cells[1], CONTRACTOR, "Генеральный директор",
             "_______________ / Ядрихинский С.А."),
        ):
            cell.text = ""
            for i, line in enumerate(lines + ["", post, "", sign]):
                par = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
                run = par.add_run(line)
                run.font.size = Pt(9)
                if i == 0:
                    run.bold = True
                par.paragraph_format.space_after = Pt(1)

    return p, h, bullets, signatures


