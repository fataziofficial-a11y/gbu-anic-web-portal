def new_doc():
    doc = Document()
    sec = doc.sections[0]
    sec.page_height, sec.page_width = Cm(29.7), Cm(21.0)
    sec.left_margin = sec.right_margin = Cm(2.0); sec.top_margin = sec.bottom_margin = Cm(1.8)
    base = doc.styles["Normal"]; base.font.name = "Calibri"; base.font.size = Pt(11)
    base.element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    for name, size in (("Heading 1", 15), ("Heading 2", 12.5)):
        s = doc.styles[name]; s.font.name = "Calibri"; s.font.size = Pt(size); s.font.color.rgb = ACCENT; s.font.bold = True
        s.element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    return doc


def shade(cell, hex_):
    tcPr = cell._tc.get_or_add_tcPr(); sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), hex_); tcPr.append(sh)


class D:
    def __init__(self, title, subtitle):
        self.doc = new_doc()
        self.p("ГБУ «Арктический научно-исследовательский центр Республики Саха (Якутия)»", size=10, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=2)
        self.p("Официальный сайт аниц.рф", size=10, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=18)
        self.p(title, bold=True, size=18, color=ACCENT, align=WD_ALIGN_PARAGRAPH.CENTER, after=4)
        self.p(subtitle, size=11, italic=True, align=WD_ALIGN_PARAGRAPH.CENTER, after=4)
        self.p("Договор № 01/09/26-2 · Исполнитель ООО «АСТРА ГРУПП» · октябрь 2026", size=9.5, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=16)

    def p(self, text, bold=False, size=None, italic=False, color=None, align=None, after=5):
        para = self.doc.add_paragraph(); r = para.add_run(text); r.bold = bold; r.italic = italic
        if size: r.font.size = Pt(size)
        if color: r.font.color.rgb = color
        if align is not None: para.alignment = align
        para.paragraph_format.space_after = Pt(after)
        return para

    def h1(self, t): self.doc.add_heading(t, level=1)
    def h2(self, t): self.doc.add_heading(t, level=2)

    def li(self, text, lead=None):
        para = self.doc.add_paragraph(style="List Bullet")
        if lead: r = para.add_run(lead); r.bold = True
        para.add_run(text); para.paragraph_format.space_after = Pt(2)

    def steps(self, items):
        for t in items:
            para = self.doc.add_paragraph(style="List Number"); para.add_run(t); para.paragraph_format.space_after = Pt(2)

    def note(self, text): self.p(text, size=9.5, italic=True, color=GREY)

    def code(self, text):
        para = self.doc.add_paragraph(); r = para.add_run(text); r.font.name = "Consolas"; r.font.size = Pt(9.5)
        r.element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas"); para.paragraph_format.space_after = Pt(6)
        para.paragraph_format.left_indent = Cm(0.5)

    def table(self, headers, rows, widths, first_bold=True):
        t = self.doc.add_table(rows=1, cols=len(headers)); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for i, h in enumerate(headers):
            c = t.rows[0].cells[i]; r = c.paragraphs[0].add_run(h); r.bold = True; r.font.size = Pt(9.5)
            r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF); shade(c, "0E4A6E")
        for row in rows:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                para = cells[i].paragraphs[0]
                for j, line in enumerate(str(v).split("\n")):
                    if j: para = cells[i].add_paragraph()
                    r = para.add_run(line); r.font.size = Pt(9.5)
                    if first_bold and i == 0: r.bold = True
                    para.paragraph_format.space_after = Pt(1)
        for row in t.rows:
            for i, w in enumerate(widths): row.cells[i].width = Cm(w)
        self.doc.add_paragraph()

    def save(self, name):
        path = os.path.join(OUT, name); self.doc.save(path); print("saved", path)


